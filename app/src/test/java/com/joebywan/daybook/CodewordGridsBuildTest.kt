package com.joebywan.daybook

import com.joebywan.daybook.core.Difficulty
import com.joebywan.daybook.core.Rng
import com.joebywan.daybook.puzzles.CodewordLogic
import com.joebywan.daybook.puzzles.CodewordTeacher
import com.joebywan.daybook.puzzles.CodewordWords
import com.joebywan.daybook.puzzles.WheelWords
import com.joebywan.daybook.puzzles.WordWheelWords
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import java.util.concurrent.Executors

/**
 * Builds `puzzles/CodewordGrids.kt`, the grids Codeword's boards come from. Not a check: it runs only when asked,
 *
 *     DAYBOOK_CODEWORD_GRIDS=app/src/main/java/com/joebywan/daybook/puzzles/CodewordGrids.kt \
 *         ./gradlew :app:testDebugUnitTest --tests '*CodewordGridsBuildTest*' --rerun
 *
 * and writes the same file every time: draw `i` of a tier uses `Rng(seed(tier, i))` alone, the draws are split across
 * threads but read back in draw order, and a tier keeps its first [PER_TIER] grids in that order.
 *
 * A draw is a block pattern and a dense fill ([CrosswordFill], from Word Wheel's grid lists less [SKIP]); then every
 * letter given, and letters taken back in an order the `Rng` shuffles while the tier's ladder (up to
 * [CodewordLogic.Spec.needs]) still finishes the board, keeping at least one. Kept only when the walk needs the tier's
 * deepest step at least once (Hard and Expert), and [CodewordLogic.solve] finds exactly one answer both with the grid
 * lists (what the device proves again) and with [WordWheelWords.BONUS] added (so no less common word opens a second).
 *
 * Why offline: a fill is a backtracking search whose cost varies wildly with the pattern (most 11x11 patterns give up
 * within the budget), and the take-back runs the ladder once per letter.
 */
class CodewordGridsBuildTest {

    /** The pattern a tier draws: runs of 3 to [maxRun] squares, about [blacks] black squares. */
    class Shape(val maxRun: Int, val blacks: Int)

    @Test
    fun build() {
        val out = System.getenv("DAYBOOK_CODEWORD_GRIDS")
        assumeTrue("set DAYBOOK_CODEWORD_GRIDS to build the list", out != null)
        val only = System.getenv("DAYBOOK_CODEWORD_TIER")?.let { Difficulty.valueOf(it) }
        val pool = Executors.newFixedThreadPool(THREADS)
        System.getenv("DAYBOOK_CODEWORD_SWEEP")?.let { sweep ->
            // Probing shapes: "7,14;6,15" tries each on the one tier for [MAX_DRAWS]-limited batches, and writes nothing.
            for (sh in sweep.split(";")) {
                sweepShape = sh.split(",").let { Shape(it[0].toInt(), it[1].toInt()) }
                for (i in 0 until FAILS.length()) FAILS.set(i, 0)
                println("shape $sh")
                buildTier(only!!, pool, limit = SWEEP_DRAWS)
            }
            pool.shutdown()
            return
        }
        val tiers = Difficulty.entries.filter { only == null || it == only }.associateWith { tier -> buildTier(tier, pool) }
        pool.shutdown()
        File(out!!).writeText(source(tiers))
    }

    private fun buildTier(tier: Difficulty, pool: java.util.concurrent.ExecutorService, limit: Int = MAX_DRAWS): List<String> {
        val found = mutableListOf<String>()
        val seen = HashSet<String>() // probed only, never iterated
        var drawn = 0
        val started = System.nanoTime()
        val want = System.getenv("DAYBOOK_CODEWORD_PER_TIER")?.toInt() ?: PER_TIER
        while (found.size < want && drawn < limit) {
            val futures = (drawn until drawn + BATCH).map { i -> pool.submit<String?> { make(tier, Rng(seed(tier, i))) } }
            for (f in futures) {
                val e = f.get() ?: continue
                if (found.size < want && seen.add(e.substringBefore(':'))) found += e
            }
            drawn += BATCH
            println("$tier drawn $drawn kept ${found.size} fails ${FAILS.toString()} (${(System.nanoTime() - started) / 1_000_000_000} s)")
        }
        stats(tier, found, drawn)
        return found.sorted()
    }

    private fun stats(tier: Difficulty, found: List<String>, drawn: Int) {
        if (found.isEmpty()) return
        val entries = found.map { CodewordLogic.parse(it) }
        val givens = entries.map { it.givens.length }
        val letters = entries.map { it.alphabet.size }
        val blacks = entries.map { e -> e.squares.count { it == '#' } }
        println(
            "$tier: ${found.size} of $drawn draws; givens mean ${"%.2f".format(givens.average())} (${givens.min()}-${givens.max()}), " +
                "letters mean ${"%.1f".format(letters.average())} (${letters.min()}-${letters.max()}), black squares mean ${"%.1f".format(blacks.average())}",
        )
    }

    private fun source(tiers: Map<Difficulty, List<String>>): String = buildString {
        appendLine("package com.joebywan.daybook.puzzles")
        appendLine()
        appendLine("// GENERATED by CodewordGridsBuildTest from Word Wheel's grid lists. Do not edit by hand: a board is picked by")
        appendLine("// index into these sorted lists, so reordering changes every daily board. An entry is the grid in reading order")
        appendLine("// (`#` black), `:`, the given letters. Each list is chunks of space-separated entries, because a JVM string")
        appendLine("// constant is capped at 64 KB.")
        appendLine()
        appendLine("internal object CodewordGrids {")
        for ((tier, list) in tiers) {
            appendLine("    val ${tier.name}: List<String> = listOf(")
            for (chunk in list.chunked(CHUNK)) appendLine("        \"${chunk.joinToString(" ")}\",")
            appendLine("    ).joinToString(\" \").split(\" \")")
            if (tier != tiers.keys.last()) appendLine()
        }
        appendLine("}")
    }

    companion object {
        const val SEED = 20261025L
        const val PER_TIER = 1000
        const val BATCH = 240
        const val MAX_DRAWS = 200_000
        const val SWEEP_DRAWS = 1440

        @Volatile
        var sweepShape: Shape? = null
        const val THREADS = 12
        const val CHUNK = 200
        const val BUDGET = 20_000

        /** Words the lists hold that no grid should show (the lists themselves are Lexicon's and Word Wheel's contract). */
        val SKIP = setOf("retard", "cripple")

        val SHAPES = mapOf(
            Difficulty.STANDARD to Shape(maxRun = 7, blacks = 14),
            Difficulty.HARD to Shape(maxRun = 6, blacks = 26),
            Difficulty.EXPERT to Shape(maxRun = 6, blacks = 40),
        )

        /** Why draws fail, for the log: pattern, fill, ladder, depth, proof, wide proof. */
        val FAILS = java.util.concurrent.atomic.AtomicIntegerArray(6)

        fun seed(tier: Difficulty, i: Int): Long = SEED * 1_000_003L + tier.ordinal * 10_000_019L + i

        private val INDEXES: Map<Int, CrosswordFill.Index> by lazy {
            (CodewordWords.MIN..CodewordWords.MAX).associateWith { l -> CrosswordFill.Index(WheelWords.grid(l).filter { it !in SKIP }) }
        }

        /** The grid lists with every bonus word of the same length: the wider check of uniqueness. */
        private val WIDE: Map<Int, CodewordWords.Length> by lazy {
            (CodewordWords.MIN..CodewordWords.MAX).associateWith { l ->
                CodewordWords.Length((WheelWords.grid(l) + WordWheelWords.BONUS.filter { it.length == l }).distinct().sorted())
            }
        }

        /** A letter per number when number i + 1 is [alphabet]'s i-th letter, only [givens] filled. */
        private fun lettersFor(alphabet: List<Int>, givens: Set<Int>) = alphabet.map { if (it in givens) it else CodewordLogic.EMPTY }

        /** One draw: the entry, or null when the pattern, the fill or the tier's test failed. */
        fun make(tier: Difficulty, rng: Rng): String? {
            val spec = CodewordLogic.specFor(tier)
            val shape = sweepShape ?: SHAPES.getValue(tier)
            val size = spec.size
            val white = CrosswordFill.pattern(rng, size, 3, shape.maxRun, shape.blacks) ?: return null.also { FAILS.incrementAndGet(0) }
            val grid = CrosswordFill.fill(rng, white, size, INDEXES, BUDGET) ?: return null.also { FAILS.incrementAndGet(1) }
            val squares = String(grid)
            val alphabet = squares.filter { it != '#' }.map { it - 'a' }.distinct().sorted()
            val numbers = squares.map { if (it == '#') 0 else alphabet.indexOf(it - 'a') + 1 }
            val upTo = CodewordTeacher.TECHNIQUES.indexOf(spec.needs)
            val givens = alphabet.toMutableSet()
            for (l in rng.shuffled(alphabet)) {
                if (givens.size == 1) break
                givens -= l
                if (CodewordTeacher.walk(size, numbers, lettersFor(alphabet, givens), upTo) == null) givens += l
            }
            if (givens.size == alphabet.size) return null.also { FAILS.incrementAndGet(2) }
            val letters = lettersFor(alphabet, givens)
            val walk = CodewordTeacher.walk(size, numbers, letters, upTo) ?: return null
            if (upTo > CodewordTeacher.TECHNIQUES.indexOf(CodewordTeacher.RUN_AGREES) && walk.none { it.technique == spec.needs }) return null.also { FAILS.incrementAndGet(3) }
            if (CodewordLogic.solve(size, numbers, letters) !is CodewordLogic.Verdict.ExactlyOne) return null.also { FAILS.incrementAndGet(4) }
            if (CodewordLogic.solve(size, numbers, letters) { WIDE.getValue(it) } !is CodewordLogic.Verdict.ExactlyOne) return null.also { FAILS.incrementAndGet(5) }
            return "$squares:" + givens.sorted().map { 'a' + it }.joinToString("")
        }
    }
}
