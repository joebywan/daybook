package com.joebywan.daybook

import com.joebywan.daybook.core.Difficulty
import com.joebywan.daybook.core.Rng
import com.joebywan.daybook.puzzles.CipherLogic
import com.joebywan.daybook.puzzles.CipherSum
import com.joebywan.daybook.puzzles.CipherTeacher
import com.joebywan.daybook.puzzles.WordList
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import java.util.concurrent.Executors

/**
 * Builds `puzzles/CipherSums.kt`, the sums Cipher's boards come from. Not a check: it runs only when asked,
 *
 *     DAYBOOK_CIPHER_SUMS=app/src/main/java/com/joebywan/daybook/puzzles/CipherSums.kt \
 *         ./gradlew :app:testDebugUnitTest --tests '*CipherSumsBuildTest*' --rerun
 *
 * and writes the same file every time (a fixed seed draws the addend pairs; the work is split across threads
 * but read back in draw order). A sum is two four-letter answer words and a five-letter answer word
 * (`LexiconWords`, so every word is screened and well known) with exactly one answer that the teacher's ladder
 * finishes. Each addend pair gives at most one sum, its first total in alphabetical order, and that sum's
 * tier is the hardest technique the ladder needs for it ([tierOf]). Drawing stops once every tier is full.
 *
 * Why offline: about one pair in four has such a total, and finding it means proving each of the 1,801
 * five-letter totals (~7 ms a pair on 12 desktop threads; a phone has one, and the web one slower thread).
 * Why 4 + 4 = 5: the total's extra letter is the leading carry, the foothold every hand-solved sum starts
 * from. Measured over 3,000 draws, two five-letter addends (no foothold) gave one ladder board per 30
 * pairs and three addends none, though both have plenty with one answer: they need trial, not columns.
 */
class CipherSumsBuildTest {

    @Test
    fun build() {
        val out = System.getenv("DAYBOOK_CIPHER_SUMS")
        assumeTrue("set DAYBOOK_CIPHER_SUMS to build the list", out != null)
        val fours = WordList.answers(4)
        val fives = WordList.answers(5)
        val rng = Rng(SEED)
        val seen = HashSet<String>() // probed only, never iterated
        val tiers = Difficulty.entries.associateWith { mutableListOf<String>() }
        val pool = Executors.newFixedThreadPool(THREADS)
        var drawn = 0
        while (tiers.values.any { it.size < PER_TIER }) {
            val batch = mutableListOf<Pair<String, String>>()
            while (batch.size < BATCH) {
                val a = rng.pick(fours)
                val b = rng.pick(fours)
                if (a == b || !seen.add(minOf(a, b) + maxOf(a, b))) continue
                batch += a to b
            }
            drawn += batch.size
            val found = batch.map { (a, b) ->
                pool.submit<Pair<String, Difficulty>?> {
                    fives.firstNotNullOfOrNull { t ->
                        val sum = CipherSum(listOf(a, b, t))
                        if (!sum.wellFormed || CipherLogic.prove(sum) !is CipherLogic.Verdict.ExactlyOne ||
                            !CipherTeacher.solvesByLogic(sum)
                        ) null else "$a+$b=$t" to tierOf(sum)
                    }
                }
            }.mapNotNull { it.get() }
            for ((entry, tier) in found) tiers.getValue(tier).let { if (it.size < PER_TIER) it += entry }
            println("drawn $drawn: " + tiers.map { "${it.key} ${it.value.size}" })
        }
        pool.shutdown()
        File(out!!).writeText(source(tiers.mapValues { it.value.sorted() }, drawn))
    }

    private fun source(tiers: Map<Difficulty, List<String>>, drawn: Int): String = buildString {
        appendLine("package com.joebywan.daybook.puzzles")
        appendLine()
        appendLine("// GENERATED by CipherSumsBuildTest from LexiconWords' answer lists ($drawn addend pairs drawn). Do not edit by")
        appendLine("// hand: a board is picked by index into these sorted lists, so reordering changes every daily board.")
        appendLine("// Each list is chunks of space-separated sums, because a JVM string constant is capped at 64 KB.")
        appendLine()
        appendLine("internal object CipherSums {")
        for ((tier, list) in tiers) {
            appendLine("    val ${tier.name}: List<String> = listOf(")
            for (chunk in list.chunked(CHUNK)) appendLine("        \"${chunk.joinToString(" ")}\",")
            appendLine("    ).joinToString(\" \").split(\" \")")
            if (tier != Difficulty.EXPERT) appendLine()
        }
        appendLine("}")
    }

    companion object {
        const val SEED = 20261022L
        const val PER_TIER = 1200
        const val BATCH = 1200
        const val THREADS = 12
        const val CHUNK = 300

        /** Standard: columns alone or two at a time. Hard: every column together. Expert: a what-if on two columns. */
        internal fun tierOf(sum: CipherSum): Difficulty {
            val used = CipherTeacher.walk(sum)!!.map { it.technique }.toSet()
            return when {
                CipherTeacher.WHAT_IF in used -> Difficulty.EXPERT
                CipherTeacher.CHAIN in used -> Difficulty.HARD
                else -> Difficulty.STANDARD
            }
        }
    }
}
