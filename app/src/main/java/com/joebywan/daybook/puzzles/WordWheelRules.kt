package com.joebywan.daybook.puzzles

import com.joebywan.daybook.core.Difficulty
import com.joebywan.daybook.core.Rng
import kotlinx.serialization.Serializable

/**
 * One word of the grid: [word] written from square ([row], [col]) across or down. Its squares are numbered
 * `row * width + col` on the board, which is also what a highlight index means for them.
 */
/** Letter [i] of a slot starting at ([row], [col]) on a [width]-wide grid, as `row * width + col`. */
internal fun slotCell(row: Int, col: Int, across: Boolean, i: Int, width: Int): Int =
    if (across) row * width + col + i else (row + i) * width + col

@Serializable
data class WheelSlot(val word: String, val row: Int, val col: Int, val across: Boolean) {
    val length: Int get() = word.length

    /** The square of letter [i], as `row * width + col`. */
    fun cell(i: Int, width: Int): Int = slotCell(row, col, across, i, width)

    fun cells(width: Int): List<Int> = List(word.length) { cell(it, width) }
}

/**
 * Word Wheel's board: the [wheel] of letters, a small crossword of [slots] on a [width] x [height] grid, the grid words
 * [found] so far and the [bonus] words (real words from the wheel that are not in the grid), both in the order found.
 *
 * Slot 0 is always the wheel's own word, all of its letters. Every slot holds a different word, and a typed word goes to
 * the slot it was laid for: two empty slots of one length that could both take it never compete for it, because only
 * one of them holds it. The word being spelled is never state (it lives in the board's `remember`), so one accepted
 * word is one state and one undo.
 *
 * Saves hold the words themselves, so a game written today loads whatever the lists do later.
 */
@Serializable
data class WordWheelState(
    val wheel: String,
    val width: Int,
    val height: Int,
    val slots: List<WheelSlot>,
    val found: List<String> = emptyList(),
    val bonus: List<String> = emptyList(),
    override val moves: Int = 0,
) : PuzzleState {

    /** The rule: every slot holds its word. */
    override val solved: Boolean get() = slots.all { it.word in found }

    fun filled(slot: Int): Boolean = slots[slot].word in found

    /** The letter showing in each square: the letters of found words, null where nothing is found yet or no slot runs. */
    fun shown(): Array<Char?> {
        val out = arrayOfNulls<Char>(width * height)
        for (slot in slots) if (slot.word in found) slot.cells(width).forEachIndexed { i, c -> out[c] = slot.word[i] }
        return out
    }

    /** Whether some slot runs through each square. */
    fun used(): BooleanArray {
        val out = BooleanArray(width * height)
        for (slot in slots) slot.cells(width).forEach { out[it] = true }
        return out
    }

    /** The shortest word this board takes: its shortest slot, so a board with no three-letter slot refuses three letters. */
    val shortestWord: Int get() = slots.minOf { it.word.length }

    /** The board once [word] is entered: a grid word fills its slot, a new real word joins the bonus words, anything else changes nothing. */
    fun enter(word: String): WordWheelState = when (WordWheelLogic.judge(this, word)) {
        is WheelEntry.Fills -> copy(found = found + word, moves = moves + 1)
        WheelEntry.Bonus -> copy(bonus = bonus + word, moves = moves + 1)
        else -> this
    }
}

/** What happens to a word spelled on the wheel. */
sealed interface WheelEntry {
    /** It is the word of grid slot [slot]. */
    data class Fills(val slot: Int) : WheelEntry

    /** A real word the grid does not hold: counted, shown, never required. */
    data object Bonus : WheelEntry

    /** Already in the grid or the bonus words. */
    data object Found : WheelEntry

    data object NotAWord : WheelEntry

    /** Shorter than the board's shortest slot ([WordWheelState.shortestWord]). */
    data object TooShort : WheelEntry

    /** Needs a letter the wheel has not got (or more copies of one); a swipe never makes this, a keyboard can. */
    data object NotOnWheel : WheelEntry
}

/**
 * The word lists, all generated by `tools/words/build.py` (see [WordWheelWords]) and sorted, so a board is a pick by index and
 * a word check is a binary search: no hash container near a seed.
 *
 * - [grid]: the well-known words a slot can hold, by length 3..7. Lexicon's answer screening (SCOWL 10/20/35, dialect-neutral,
 *   no inflections, minus `exclude.txt`), limited to words with a clue (`clues.txt` and `wheel-clues.txt`), because a hint
 *   gives a slot's word as its clue.
 * - [roots]: the wheels, grid words of 5, 6 and 7 letters that spell enough other grid words.
 * - Accepted words ([isWord]): the grid lists plus `BONUS`, Lexicon's guess rule at every length, kept to words some wheel can spell.
 */
object WheelWords {

    fun grid(length: Int): List<String> = when (length) {
        3 -> WordWheelWords.GRID_3
        4 -> WordWheelWords.GRID_4
        5 -> WordWheelWords.GRID_5
        6 -> WordWheelWords.GRID_6
        7 -> WordWheelWords.GRID_7
        else -> emptyList()
    }

    fun roots(length: Int): List<String> = when (length) {
        5 -> WordWheelWords.ROOTS_5
        6 -> WordWheelWords.ROOTS_6
        7 -> WordWheelWords.ROOTS_7
        else -> error("no $length-letter wheels")
    }

    fun isGridWord(word: String): Boolean = grid(word.length).binarySearch(word) >= 0

    /** Whether [word] is accepted at all: a grid word or a bonus word. */
    fun isWord(word: String): Boolean = isGridWord(word) || WordWheelWords.BONUS.binarySearch(word) >= 0

    // Probed by word, never iterated, so its order cannot reach a seed.
    private val clues: Map<String, String> by lazy {
        WordWheelClueText.ALL.split("\n").associate { it.substringBefore(": ") to it.substringAfter(": ") }
    }

    /** A crossword-style clue for a grid [word]: Lexicon's for four and five letters, Word Wheel's own for the rest. */
    fun clue(word: String): String = clues[word] ?: WordList.clue(word)

    /** Whether [word] can be spelled from [wheel], each letter of the wheel used at most once. */
    fun spellable(word: String, wheel: String): Boolean {
        val left = IntArray(26)
        for (c in wheel) left[c - 'a']++
        for (c in word) if (--left[c - 'a'] < 0) return false
        return true
    }

    /** Every grid word of three letters or more that [wheel] spells, shortest first, then in list order. */
    fun gridWordsFrom(wheel: String): List<String> =
        (3..wheel.length).flatMap { n -> grid(n).filter { spellable(it, wheel) } }
}

/**
 * Word Wheel's rules and generator, with no screen.
 *
 * **Layout rules** (what [lay] obeys and `WordWheelOracle` re-checks from the squares alone): words run across or down; two
 * words share a square only where they cross, one across and one down, on the same letter; a word's new squares never touch
 * another word's squares side by side, and nothing sits just before its first letter or just after its last, so every
 * run of two or more letters in a row or column is exactly one placed word; every word crosses one already placed, so the
 * grid is connected.
 *
 * **Generation** ([generateVerified]): a root of the tier's length is picked by index from [WheelWords.roots]; its grid words
 * are shuffled with the seed's [Rng] (from the sorted list, so no hash order can reach it), longest first, and each is laid
 * crossing the grid at a place drawn from those with the most crossings that keep the grid inside the tier's box. A board
 * ships only if it reaches the tier's word count (and, on Expert, holds a six-letter word besides the root) and is
 * winnable without luck: walking it by hints alone, the next slot always has at most [MAX_CHOICE] grid words that fit it
 * ([WordWheelTeacher.walk]).
 */
internal object WordWheelLogic {

    /** A tier: the wheel's size, how many words the grid holds, the box it must fit, and whether it needs a six beside the root. */
    class Spec(val letters: Int, val minWords: Int, val maxWords: Int, val maxCols: Int, val maxRows: Int, val needSix: Boolean)

    fun specFor(difficulty: Difficulty): Spec = when (difficulty) {
        Difficulty.STANDARD -> Spec(5, 4, 6, 6, 6, false)
        Difficulty.HARD -> Spec(6, 6, 8, 7, 7, false)
        Difficulty.EXPERT -> Spec(7, 8, 11, 8, 8, true)
    }

    const val ATTEMPTS = 40

    /** The most grid words that may fit the easiest empty slot at any step of the hints-alone walk. */
    const val MAX_CHOICE = 6

    fun generateVerified(seed: Long, difficulty: Difficulty): WordWheelState? {
        val spec = specFor(difficulty)
        val roots = WheelWords.roots(spec.letters)
        for (attempt in 0 until ATTEMPTS) {
            val rng = Rng(seed + attempt)
            val root = roots[rng.nextInt(roots.size)]
            val board = lay(root, spec, rng) ?: continue
            if (WordWheelTeacher.walk(board).maxChoice > MAX_CHOICE) continue
            return board
        }
        return null
    }

    fun judge(s: WordWheelState, word: String): WheelEntry {
        // First: a saved game can hold a bonus word shorter than the board now takes.
        if (word in s.found || word in s.bonus) return WheelEntry.Found
        if (word.length < s.shortestWord) return WheelEntry.TooShort
        if (!WheelWords.spellable(word, s.wheel)) return WheelEntry.NotOnWheel
        val slot = s.slots.indexOfFirst { it.word == word }
        if (slot >= 0) return WheelEntry.Fills(slot)
        return if (WheelWords.isWord(word)) WheelEntry.Bonus else WheelEntry.NotAWord
    }

    /** The wheel's letters in the order the board shows them first: shuffled, and never spelling the root outright. */
    private fun scramble(root: String, rng: Rng): String {
        val s = rng.shuffled(root.toList()).joinToString("")
        return if (s == root) s.drop(1) + s.first() else s
    }

    /** A placement being considered (one of those with the most crossings). */
    private class Place(val row: Int, val col: Int, val across: Boolean)

    /**
     * Lays [root] and as many of its grid words as the tier asks for, or null when it cannot. Squares live in a probe-only
     * map keyed by position (never iterated); everything iterated is a list in placement order.
     */
    fun lay(root: String, spec: Spec, rng: Rng): WordWheelState? {
        val wheel = scramble(root, rng)
        val target = rng.nextInt(spec.minWords, spec.maxWords)
        val pool = rng.shuffled(WheelWords.gridWordsFrom(root).filter { it != root }).sortedByDescending { it.length }

        // Coordinates are unbounded while laying (offset so they stay positive) and shifted to 0 at the end.
        val grid = HashMap<Int, Char>() // probe-only
        val across = HashMap<Int, Boolean>() // probe-only: the one direction a square's word runs, or absent once crossed
        val crossed = HashSet<Int>() // probe-only
        fun key(r: Int, c: Int) = (r + OFF) * SPAN + (c + OFF)
        val placed = mutableListOf(WheelSlot(root, 0, 0, true))
        var minR = 0
        var maxR = 0
        var minC = 0
        var maxC = root.length - 1
        fun put(w: String, r: Int, c: Int, a: Boolean) {
            for (i in w.indices) {
                val k = if (a) key(r, c + i) else key(r + i, c)
                if (grid.containsKey(k)) {
                    crossed += k
                    across.remove(k)
                } else {
                    grid[k] = w[i]
                    across[k] = a
                }
            }
            minR = minOf(minR, r)
            minC = minOf(minC, c)
            maxR = maxOf(maxR, if (a) r else r + w.length - 1)
            maxC = maxOf(maxC, if (a) c + w.length - 1 else c)
        }
        put(root, 0, 0, true)

        /** Crossings if [w] fits at ([r], [c]) running across ([a]) or down, else -1. */
        fun fits(w: String, r: Int, c: Int, a: Boolean): Int {
            val dr = if (a) 0 else 1
            val dc = if (a) 1 else 0
            if (grid.containsKey(key(r - dr, c - dc)) || grid.containsKey(key(r + dr * w.length, c + dc * w.length))) return -1
            var crossings = 0
            for (i in w.indices) {
                val rr = r + dr * i
                val cc = c + dc * i
                val k = key(rr, cc)
                val have = grid[k]
                if (have != null) {
                    if (have != w[i] || k in crossed || across[k] == a) return -1
                    crossings++
                } else if (grid.containsKey(key(rr + dc, cc + dr)) || grid.containsKey(key(rr - dc, cc - dr))) {
                    return -1
                }
            }
            if (crossings == 0 || crossings == w.length) return -1
            val h = maxOf(maxR, r + dr * (w.length - 1)) - minOf(minR, r) + 1
            val wd = maxOf(maxC, c + dc * (w.length - 1)) - minOf(minC, c) + 1
            return if (h > spec.maxRows || wd > spec.maxCols) -1 else crossings
        }

        val left = pool.toMutableList()
        var progress = true
        while (placed.size < target && progress) {
            progress = false
            var i = 0
            while (i < left.size && placed.size < target) {
                val w = left[i]
                val options = mutableListOf<Place>()
                var best = 0
                for (slot in placed) {
                    for (j in slot.word.indices) {
                        val r0 = if (slot.across) slot.row else slot.row + j
                        val c0 = if (slot.across) slot.col + j else slot.col
                        if (key(r0, c0) in crossed) continue
                        val a = !slot.across
                        for (k in w.indices) {
                            if (w[k] != slot.word[j]) continue
                            val r = if (a) r0 else r0 - k
                            val c = if (a) c0 - k else c0
                            val n = fits(w, r, c, a)
                            if (n < 0) continue
                            if (n > best) {
                                best = n
                                options.clear()
                            }
                            if (n == best) options += Place(r, c, a)
                        }
                    }
                }
                if (options.isEmpty()) {
                    i++
                    continue
                }
                val p = options[rng.nextInt(options.size)]
                put(w, p.row, p.col, p.across)
                placed += WheelSlot(w, p.row, p.col, p.across)
                left.removeAt(i)
                progress = true
            }
        }
        if (placed.size < spec.minWords) return null
        if (spec.needSix && placed.drop(1).none { it.length >= 6 }) return null
        return WordWheelState(
            wheel = wheel,
            width = maxC - minC + 1,
            height = maxR - minR + 1,
            slots = placed.map { it.copy(row = it.row - minR, col = it.col - minC) },
        )
    }

    private const val OFF = 32
    private const val SPAN = 64

    /** The seed [lastResort] lays: a fixed board per tier, proved (and pinned) by `WordWheelRulesTest`, as Regions does. */
    const val LAST_RESORT_SEED = 1L

    /** The board for the day nothing was proved (a year per tier never reaches it, `FallbackTest`). */
    fun lastResort(difficulty: Difficulty): WordWheelState =
        generateVerified(LAST_RESORT_SEED, difficulty) ?: error("the fixed last-resort seed no longer proves a board")
}
