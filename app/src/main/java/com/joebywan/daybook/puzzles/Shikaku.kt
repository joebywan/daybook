/** An axis-aligned block of cells, inclusive on both corners. */
@Serializable
data class Block(val r0: Int, val c0: Int, val r1: Int, val c1: Int) {
    val area: Int get() = (r1 - r0 + 1) * (c1 - c0 + 1)
    fun contains(r: Int, c: Int) = r in r0..r1 && c in c0..c1
    fun overlaps(other: Block) =
        r0 <= other.r1 && other.r0 <= r1 && c0 <= other.c1 && other.c0 <= c1
}

@Serializable
data class ShikakuState(
    val width: Int,
    val height: Int,
    val clues: List<Int?>,
    val blocks: List<Block>,
    val solution: List<Block>,
    override val moves: Int = 0,
) : PuzzleState {

    /** The rules, not a comparison with [solution]; see [Shikaku.isSolved]. */
    override val solved: Boolean get() = Shikaku.isSolved(width, height, clues, blocks)

    /** Adds a block, evicting anything it overlaps. Rejects blocks that hold other than one clue. */
    fun place(block: Block): ShikakuState {
        val cluesInside = (block.r0..block.r1).sumOf { r ->
            (block.c0..block.c1).count { c -> clues[r * width + c] != null }
        }
        val kept = blocks.filterNot { it.overlaps(block) }
        // A block with no clue just clears the area; a block with two or more is never legal.
        val next = if (cluesInside == 1) kept + block else kept
        return copy(blocks = next, moves = moves + 1)
    }

    fun blockAt(r: Int, c: Int): Block? = blocks.firstOrNull { it.contains(r, c) }
}

/**
 * Shikaku — cut the grid into rectangles, one number each, the number being the area.
 *
 * Generated by growing a random tiling of the grid, then a clue in each rectangle; the draw is
 * re-rolled until the clues admit only that one tiling and the hints need what the tier asks for.
 */
object Shikaku : PuzzleType {

    override val id = "shikaku"
    override val displayName = "Shikaku"
    override val tagline = "Cut the grid into numbered rectangles"
    override val accent = 0xFFE0B23C
    override val rules = listOf(
        "Divide the whole grid into rectangles.",
        "Every rectangle must contain exactly one number.",
        "That number is the rectangle's area in squares.",
        "Drag from one corner to another to draw a rectangle. Tap a rectangle to remove it.",
    )

    /**
     * Whether [blocks] is a finished board: every block inside the grid, no two overlapping, every
     * square covered, and each block holding exactly one number, equal to its area. Reads only the
     * clues and the blocks, never a stored answer.
     */
    fun isSolved(width: Int, height: Int, clues: List<Int?>, blocks: List<Block>): Boolean {
        if (clues.size != width * height) return false
        val owner = BooleanArray(width * height)
        for (b in blocks) {
            if (b.r0 < 0 || b.c0 < 0 || b.r1 >= height || b.c1 >= width || b.r1 < b.r0 || b.c1 < b.c0) return false
            var numbered = 0
            var number = 0
            for (r in b.r0..b.r1) for (c in b.c0..b.c1) {
                val i = r * width + c
                if (owner[i]) return false
                owner[i] = true
                clues[i]?.let { numbered++; number = it }
            }
            if (numbered != 1 || number != b.area) return false
        }
        return owner.all { it }
    }

    private fun shape(difficulty: Difficulty) = when (difficulty) {
        Difficulty.STANDARD -> Triple(6, 7, 6)
        Difficulty.HARD -> Triple(8, 9, 8)
        Difficulty.EXPERT -> Triple(9, 11, 10)
    }

    override fun generate(seed: Long, difficulty: Difficulty): PuzzleState =
        generateVerified(seed, difficulty) ?: lastResort(difficulty)

    /**
     * The real generator: a board whose single tiling has been *proved* by [countTilings] and whose
     * hint walk, from the blank board, finishes without the fallback and needs what its tier asks
     * for ([accepts]); or null when no draw in the [ATTEMPTS] budget did. Split out from [generate]
     * so a test can assert the last resort is never what ships.
     *
     * Each draw is a tiling grown by [tile] (null, and redrawn, when it boxes a square in), then one
     * clue per rectangle. On Expert the clue stays off a rectangle's corners where it has any other
     * square: a corner clue tells the player two of the rectangle's sides, so moving it inward
     * measurably deepened Expert boards (needing common cells or a what-if: 22% to 27% of proved draws).
     */
    internal fun generateVerified(seed: Long, difficulty: Difficulty): ShikakuState? {
        val (w, h, maxArea) = shape(difficulty)

        for (attempt in 0 until ATTEMPTS) {
            val rng = Rng(seed + attempt)
            val blocks = tile(rng, w, h, maxArea) ?: continue
            val clues = MutableList<Int?>(w * h) { null }
            blocks.forEach { b ->
                val cells = (b.r0..b.r1).flatMap { r -> (b.c0..b.c1).map { c -> r * w + c } }
                val inner = if (difficulty == Difficulty.EXPERT && b.r1 > b.r0 && b.c1 > b.c0) {
                    cells.filterNot { (it / w == b.r0 || it / w == b.r1) && (it % w == b.c0 || it % w == b.c1) }
                } else emptyList()
                val pool = inner.ifEmpty { cells }
                clues[pool[rng.nextInt(pool.size)]] = b.area
            }
            if (countTilings(w, h, clues) == 1 && accepts(difficulty, depth(w, h, clues))) {
                return ShikakuState(w, h, clues.toList(), emptyList(), blocks)
            }
        }
        return null
    }

    /**
     * How many draws are tried before [generate] gives up and takes [lastResort]. Most draws are
     * cheap refusals (a boxed-in square, about 70% of them); a year of daily seeds per tier needs at
     * most a few hundred (`FallbackTest`, `docs/TEACHING.md`), so the budget sits well past the worst.
     */
    private const val ATTEMPTS = 2000

    /**
     * What each tier asks of a board's hint walk ([depth], an index into [ShikakuTeacher.TECHNIQUES]):
     * never the fallback; Standard nothing past only-reaches, Hard something past only-fits, Expert
     * at least one common-cells or what-if. Measured in `docs/TEACHING.md` ("Tier depth").
     */
    private fun accepts(difficulty: Difficulty, depth: Int?): Boolean {
        depth ?: return false
        return when (difficulty) {
            Difficulty.STANDARD -> depth <= REACHES
            Difficulty.HARD -> depth >= REACHES
            Difficulty.EXPERT -> depth >= COMMON
        }
    }

    private val REACHES = ShikakuTeacher.TECHNIQUES.indexOf(ShikakuTeacher.ONLY_REACHES)
    private val COMMON = ShikakuTeacher.TECHNIQUES.indexOf(ShikakuTeacher.COMMON_CELLS)

    /**
     * The deepest technique (an index into [ShikakuTeacher.TECHNIQUES]) the hints need to finish the
     * blank board, drawing each step's rectangle; null when they get stuck, which is a board whose
     * hints would fall back. Every step is sound, so a walk that finishes also proves the answer.
     */
    internal fun depth(w: Int, h: Int, clues: List<Int?>): Int? {
        val blocks = mutableListOf<Block>()
        var deepest = 0
        repeat(clues.count { it != null }) {
            val step = ShikakuTeacher.deduce(w, h, clues, blocks) ?: return null
            deepest = maxOf(deepest, ShikakuTeacher.TECHNIQUES.indexOf(step.technique))
            blocks += step.place ?: return null
        }
        return deepest
    }

    /** The seed [lastResort] draws from. */
    private const val LAST_RESORT_SEED = 20261025L

    /**
     * What ships for a seed [generateVerified] did not prove: the board of one fixed seed, which is
     * itself proved and gated. A pure function of the tier; `ShikakuClueTest` asserts it is proved
     * on every tier, so this cannot throw once that test is green. A year per tier never reaches it.
     */
    internal fun lastResort(difficulty: Difficulty): ShikakuState =
        generateVerified(LAST_RESORT_SEED, difficulty) ?: error("the fixed last-resort seed no longer proves a board")

    /**
     * The smallest rectangle a tiling may hold, and so the smallest clue any board can carry.
     *
     * A clue of 1 names the square it is printed on, so it is answered by seeing it rather than by
     * working anything out, and it is the one rectangle a player cannot draw cleanly: a 1x1 drag is
     * the degenerate drag, indistinguishable from a slipped tap. Every clue is the area of the
     * block it came from, so never *laying* a 1 is what keeps 1 off the board.
     */
    private const val MIN_AREA = 2

    /**
     * A random tiling of the grid into rectangles of [MIN_AREA] to [maxArea] squares, or null when a
     * square is boxed in with no rectangle left to cover it (the caller redraws).
     *
     * Fills in reading order: the first uncovered square must be the top-left corner of whatever
     * covers it, so each step picks uniformly among the rectangles rooted there that fit. Unlike
     * the recursive bisection this replaced, nothing forces a cut across the whole grid, so
     * pinwheels and other non-guillotine layouts appear (about half of proved boards; `ShikakuClueTest`).
     */
    private fun tile(rng: Rng, w: Int, h: Int, maxArea: Int): List<Block>? {
        val taken = BooleanArray(w * h)
        val blocks = mutableListOf<Block>()
        while (true) {
            val hole = taken.indexOfFirst { !it }
            if (hole < 0) return blocks
            val r0 = hole / w
            val c0 = hole % w
            val options = mutableListOf<Block>()
            for (rows in 1..h - r0) {
                val r1 = r0 + rows - 1
                if (taken[r1 * w + c0]) break
                for (cols in 1..w - c0) {
                    val c1 = c0 + cols - 1
                    if ((r0..r1).any { taken[it * w + c1] } || rows * cols > maxArea) break
                    if (rows * cols >= MIN_AREA) options += Block(r0, c0, r1, c1)
                }
            }
            if (options.isEmpty()) return null
            val b = options[rng.nextInt(options.size)]
            blocks += b
            for (r in b.r0..b.r1) for (c in b.c0..b.c1) taken[r * w + c] = true
        }
    }

    // ---- solver -------------------------------------------------------------------------------

    /** Counts perfect tilings consistent with the clues, stopping at two. */
    private fun countTilings(w: Int, h: Int, clues: List<Int?>): Int {
        val clueCells = clues.indices.filter { clues[it] != null }
        val candidates = clueCells.map { cell ->
            val cr = cell / w
            val cc = cell % w
            val area = clues[cell]!!
            buildList {
                for (height in 1..area) {
                    if (area % height != 0) continue
                    val width = area / height
                    for (r0 in maxOf(0, cr - height + 1)..cr) {
                        for (c0 in maxOf(0, cc - width + 1)..cc) {
                            val r1 = r0 + height - 1
                            val c1 = c0 + width - 1
                            if (r1 >= h || c1 >= w) continue
                            val block = Block(r0, c0, r1, c1)
                            // A rectangle may never swallow a second clue.
                            val clueCount = (r0..r1).sumOf { r ->
                                (c0..c1).count { c -> clues[r * w + c] != null }
                            }
                            if (clueCount == 1) add(block)
                        }
                    }
                }
            }
        }

        val owner = IntArray(w * h) { -1 }
        var found = 0

        fun fits(block: Block): Boolean {
            for (r in block.r0..block.r1) for (c in block.c0..block.c1) {
                if (owner[r * w + c] != -1) return false
            }
            return true
        }

        fun mark(block: Block, value: Int) {
            for (r in block.r0..block.r1) for (c in block.c0..block.c1) owner[r * w + c] = value
        }

        fun place(placed: Int) {
            if (found >= 2) return
            if (placed == clueCells.size) {
                found++
                return
            }
            // Most-constrained clue first: the fewest still-fitting rectangles.
            var bestClue = -1
            var bestOptions: List<Block>? = null
            for (k in clueCells.indices) {
                if (owner[clueCells[k]] != -1) continue
                val options = candidates[k].filter { fits(it) }
                if (options.isEmpty()) return
                if (bestOptions == null || options.size < bestOptions.size) {
                    bestClue = k
                    bestOptions = options
                    if (options.size == 1) break
                }
            }
            val options = bestOptions ?: return
            for (block in options) {
                if (!fits(block)) continue
                mark(block, bestClue)
                place(placed + 1)
                mark(block, -1)
                if (found >= 2) return
            }
        }

        place(0)
        return found
    }

