"""Tests for tools/words/quartets.py. Run from the repo root: python3 -m unittest tools/words/test_quartets.py"""
import contextlib, io, os, sys, tempfile, unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import quartets  # noqa: E402

PLANETS = "Planets | 1 | earth jupiter mars mercury neptune saturn uranus venus"
FRUIT = "Fruit | 1 | apple banana cherry grape lemon mango pear  # trailing comment"
CLEAN = "# a comment\n\n" + PLANETS + "\n" + FRUIT + "\n"


class QuartetsTest(unittest.TestCase):
    def run_tool(self, files, *args):
        """Writes files into a fresh directory and runs the tool on it: (status, stdout, stderr, output or None)."""
        with tempfile.TemporaryDirectory() as tmp:
            src = os.path.join(tmp, "bank")
            os.mkdir(src)
            for name, text in files.items():
                with open(os.path.join(src, name), "w") as f:
                    f.write(text)
            out = os.path.join(tmp, "QuartetsWords.kt")
            stdout, stderr = io.StringIO(), io.StringIO()
            with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
                status = quartets.main(["--dir", src, "--out", out, *args])
            text = None
            if os.path.exists(out):
                with open(out) as f:
                    text = f.read()
            return status, stdout.getvalue(), stderr.getvalue(), text

    def assertFails(self, files, needle):
        status, _, err, text = self.run_tool(files)
        self.assertEqual(status, 1, err)
        self.assertIn(needle, err)
        self.assertIsNone(text)
        return err

    def test_clean_passes(self):
        status, _, err, text = self.run_tool({"a.txt": CLEAN})
        self.assertEqual(status, 0, err)
        self.assertNotIn("error", err)
        self.assertNotIn("warning", err)
        self.assertIsNotNone(text)

    def test_lint_writes_nothing(self):
        status, _, err, text = self.run_tool({"a.txt": CLEAN}, "--lint")
        self.assertEqual(status, 0, err)
        self.assertIsNone(text)

    def test_generated_text(self):
        _, _, _, text = self.run_tool({"a.txt": CLEAN + "Cost in $ \\ | 2 | dime nickel penny quarter cent dollar\n"})
        expected = (
            "package com.joebywan.daybook.puzzles\n"
            "\n"
            "// Generated by tools/words/quartets.py from tools/words/quartets/*.txt. Do not edit: change the bank and re-run it.\n"
            "\n"
            "internal object QuartetsWords {\n"
            '    /** "Title|level|word,word,...|quiet,...": words lowercase and sorted, quiet words (fit, never dealt) after the\n'
            "     *  last bar, empty when none; lines sorted by title. */\n"
            "    val CATEGORIES: List<String> = listOf(\n"
            '        "Cost in \\$ \\\\|2|cent,dime,dollar,nickel,penny,quarter|",\n'
            '        "Fruit|1|apple,banana,cherry,grape,lemon,mango,pear|",\n'
            '        "Planets|1|earth,jupiter,mars,mercury,neptune,saturn,uranus,venus|",\n'
            "    )\n"
            "}\n"
        )
        self.assertEqual(text, expected)

    def test_deterministic(self):
        files = {"b.txt": FRUIT + "\n", "a.txt": PLANETS + "\nFruit | 1 | plum\n"}
        self.assertEqual(self.run_tool(files)[3], self.run_tool(files)[3])

    def test_merges_across_files(self):
        _, _, err, text = self.run_tool({
            "a.txt": "Metals | 2 | iron copper zinc tin\n",
            "b.txt": "Metals | 2 | lead nickel tin\n" + PLANETS + "\n",
        })
        self.assertIn('"Metals|2|copper,iron,lead,nickel,tin,zinc|",', text, err)

    def test_quiet_members(self):
        status, _, err, text = self.run_tool({
            "a.txt": PLANETS + "\n" + FRUIT + "\nRed things | 2 | ~mars cherry ~apple\n",
            "b.txt": "Red things | 2 | ruby beet rose brick robin ~pear\n",
        })
        self.assertEqual(status, 0, err)
        self.assertIn('"Red things|2|beet,brick,cherry,robin,rose,ruby|apple,mars,pear",', text)
        self.assertNotIn("warning", err)

    def test_quiet_rules(self):
        six = "ruby beet rose brick robin cherry"
        self.assertFails({"a.txt": f"Red | 2 | {six} ~cherry\n"}, "both a plain and a quiet member")
        self.assertFails({"a.txt": f"Red | 2 | {six}\nRed | 2 | ~rose\n"}, "both a plain and a quiet member")
        self.assertFails({"a.txt": "Red | 2 | ruby beet rose brick robin ~cherry\n"}, "5 plain member(s), under 6")
        self.assertFails({"a.txt": f"Red | 2 | {six} ~Wine\n"}, "'Wine' is not 3 to 8 letters")
        self.assertFails({"a.txt": f"Red | 2 | {six} ~corpse\n"}, "grim.txt")
        self.assertFails({"a.txt": f"Red | 2 | {six} ~ruby\n"}, "twice on one line")
        self.assertFails({"a.txt": f"Red wine | 2 | {six} ~wine\n"}, "gives away its quiet member 'wine'")
        status, _, err, _ = self.run_tool({"a.txt": f"Red | 2 | {six} ~claret\n"})
        self.assertEqual(status, 0, err)
        self.assertIn("quiet 'claret' in 'Red' is no category's plain member", err)

    def test_level_clash(self):
        self.assertFails({"a.txt": PLANETS + "\n", "b.txt": "Planets | 2 | pluto\n"}, "b.txt:1")

    def test_bad_level(self):
        self.assertFails({"a.txt": "Fruit | 4 | apple banana cherry grape lemon mango\n"}, "level must be")

    def test_bad_word(self):
        self.assertFails({"a.txt": "Fruit | 1 | apple Banana cherry grape lemon mango\n"}, "'Banana'")
        self.assertFails({"a.txt": "Fruit | 1 | apple yu cherry grape lemon mango\n" + PLANETS}, "'yu'")
        self.assertFails({"a.txt": "Fruit | 1 | apple blackberry cherry grape lemon mango\n"}, "'blackberry'")

    def test_repeat_on_line(self):
        self.assertFails({"a.txt": "Fruit | 1 | apple apple banana cherry grape lemon mango\n"}, "twice on one line")

    def test_too_few(self):
        self.assertFails({"a.txt": "Fruit | 1 | apple banana cherry grape lemon\n"}, "under 6")

    def test_title_rules(self):
        self.assertFails({"a.txt": "A title that runs on far too long | 1 | apple banana cherry grape lemon mango\n"},
                         "over 28")
        self.assertFails({"a.txt": " | 1 | apple banana cherry grape lemon mango\n"}, "empty title")
        self.assertFails({"a.txt": 'Say "fruit" | 1 | apple banana cherry grape lemon mango\n'}, "holds")
        self.assertFails({"a.txt": "Bad|title | 1 | apple banana cherry grape lemon mango\n"}, "a '|' in the title")
        self.assertFails({"a.txt": "Apple and friends | 1 | apple banana cherry grape lemon mango\n"},
                         "gives away its member 'apple'")

    def test_member_inside_a_title_word_is_fine(self):
        status, _, err, _ = self.run_tool({"a.txt": "Pineapples | 1 | apple banana cherry grape lemon mango\n"})
        self.assertEqual(status, 0, err)

    def test_case_twin_titles(self):
        self.assertFails({"a.txt": FRUIT + "\nfruit | 1 | kiwi melon peach plum lime date\n"}, "only in case")

    def test_screened_words(self):
        self.assertFails({"a.txt": "Things | 1 | corpse banana cherry grape lemon mango\n"}, "grim.txt")
        word = sorted(quartets.read_list(os.path.join(quartets.HERE, "exclude.txt")) -
                      quartets.read_list(os.path.join(quartets.HERE, "grim.txt")))
        word = next(w for w in word if quartets.WORD.fullmatch(w))
        self.assertFails({"a.txt": f"Things | 1 | {word} banana cherry grape lemon mango\n"}, "exclude.txt")

    def test_identical_members(self):
        self.assertFails({"a.txt": FRUIT + "\nSweet things | 2 | apple banana cherry grape lemon mango pear\n"},
                         "exactly the members")

    def test_warnings(self):
        status, _, err, _ = self.run_tool({"a.txt": FRUIT + "\nYellow | 2 | banana lemon mango pear apple apples\n"})
        self.assertEqual(status, 0, err)
        self.assertIn("'apple' and 'apples'", err)
        status, _, err, _ = self.run_tool({"a.txt": FRUIT + "\nYellowish | 2 | banana lemon mango pear apple cherry\n"})
        self.assertEqual(status, 0, err)
        self.assertIn("every member of 'Yellowish' is in 'Fruit'", err)

    def test_stats(self):
        status, out, err, text = self.run_tool({"a.txt": CLEAN + "Yellow | 2 | banana lemon mango corn sun gold\n"},
                                               "--stats")
        self.assertEqual(status, 0, err)
        self.assertIsNone(text)
        self.assertIn("level 1: 2, level 2: 1, level 3: 0", out)
        self.assertIn("words in 2+ categories: 3", out)
        self.assertIn("quiet memberships: 0", out)
        self.assertIn("  banana (2): Fruit; Yellow", out)


if __name__ == "__main__":
    unittest.main()
